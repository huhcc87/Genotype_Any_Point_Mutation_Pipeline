from pathlib import Path
from datetime import datetime

def generate_markdown_report(name, sequence, mutation, pos, ref, alt,
                            enzymes, primers, gel_path=None,
                            output_path="output/report.md"):
    """Generate a clean Markdown report."""
    
    lines = []
    lines.append(f"# PCR-RFLP Design Report: {name}")
    lines.append(f"**Date:** {datetime.now().strftime('%Y-%m-%d %H:%M')}")
    lines.append("")
    lines.append("## Mutation")
    lines.append(f"- Position (1-based): {pos+1}")
    lines.append(f"- Change: {ref} → {alt}")
    lines.append(f"- Sequence length: {len(sequence)} bp")
    lines.append("")
    
    lines.append("## Best Restriction Enzymes")
    lines.append("")
    lines.append("| Enzyme | Site | Cuts WT | Cuts Mut | Score |")
    lines.append("|--------|------|---------|----------|-------|")
    for e in enzymes[:8]:
        lines.append(f"| {e['enzyme']} | {e['site']} | {e['cuts_wt']} | {e['cuts_mut']} | {e['score']} |")
    lines.append("")
    
    if enzymes:
        best = enzymes[0]
        lines.append(f"**Recommended enzyme:** `{best['enzyme']}` (recognition: {best['site']})")
        lines.append("")
    
    lines.append("## Primers")
    lines.append("")
    for p in primers[:3]:
        lines.append(f"### Pair {p['pair']} ({p.get('type', 'natural')})")
        lines.append(f"- **Forward:** `{p['forward']}` (Tm = {p['forward_tm']} °C)")
        lines.append(f"- **Reverse:** `{p['reverse']}` (Tm = {p['reverse_tm']} °C)")
        lines.append(f"- **Product size:** {p['product_size']} bp")
        lines.append("")
    
    if gel_path:
        lines.append("## Virtual Gel")
        lines.append(f"![Virtual Gel]({gel_path})")
        lines.append("")
    
    lines.append("---")
    lines.append("*Generated by Genotype Pipeline*")
    
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as f:
        f.write("\n".join(lines))
    
    return output_path
