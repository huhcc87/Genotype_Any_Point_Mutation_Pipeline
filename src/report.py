from pathlib import Path

def generate_markdown_report(
    name: str,
    mutation_info: dict,
    enzymes: list,
    primers: list,
    gel_path: str = None,
    output_path: str = "report.md"
):
    lines = []
    lines.append(f"# PCR-RFLP Design Report: {name}")
    lines.append("")
    lines.append(f"**Date:** {mutation_info.get('date', '')}")
    lines.append("")
    lines.append("## Mutation")
    lines.append(f"- Position (1-based): {mutation_info.get('position', 'N/A')}")
    lines.append(f"- Change: {mutation_info.get('ref', '?')} → {mutation_info.get('alt', '?')}")
    lines.append(f"- Sequence length: {mutation_info.get('seq_length', 'N/A')} bp")
    lines.append("")

    if enzymes:
        best = enzymes[0]
        lines.append(f"**Recommended enzyme:** `{best['enzyme']}` (recognition: {best['site']})")
        lines.append("")

        # Fragment size table
        lines.append("### Expected Fragment Sizes")
        lines.append("")
        lines.append("| Genotype | Expected Bands (bp) | Interpretation |")
        lines.append("|----------|---------------------|----------------|")
        lines.append("| Wild-type (undigested) | Full amplicon | No cut |")
        lines.append("| Wild-type (digested) | See enzyme cuts | Cut pattern |")
        lines.append("| Mutant (digested) | See enzyme cuts | Differential pattern |")
        lines.append("| Heterozygote | Both patterns | Mixed bands |")
        lines.append("")

    lines.append("## Primers")
    lines.append("")
    for p in primers[:3]:
        lines.append(f"### Pair {p['pair']} ({p.get('type', 'natural')})")
        lines.append(f"- **Forward:** `{p['forward']}` (Tm = {p['forward_tm']} °C)")
        lines.append(f"- **Reverse:** `{p['reverse']}` (Tm = {p['reverse_tm']} °C)")
        lines.append(f"- **Product size:** {p['product_size']} bp")
        lines.append("")

    if gel_path:
        lines.append("## Virtual Gel")
        lines.append(f"![Virtual Gel]({gel_path})")
        lines.append("")

    lines.append("---")
    lines.append("*Generated by Genotype Pipeline*")

    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as f:
        f.write("\n".join(lines))

    return output_path
